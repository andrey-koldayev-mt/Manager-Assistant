export function getScenario(scenarioId: string | null | undefined) {
  return OBJECTION_SCENARIOS.find((scenario) => scenario.id === scenarioId) ?? null;
}

export function getScenarioStep(scenarioId: string | null | undefined, stepId: string | null | undefined) {
  return getScenario(scenarioId)?.steps.find((step) => step.id === stepId) ?? null;
}
