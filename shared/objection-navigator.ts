type ScenarioDefinition = Omit<NavigatorScenario, 'steps'> & {
  goal: string;
  text: Partial<Record<NavigatorChannel, string>>;
  requiredVariables?: string[];
};

function scenario({ goal, text, requiredVariables = [], ...definition }: ScenarioDefinition): NavigatorScenario {
  return { ...definition, steps: [{ id: 'start', goal, text, requiredVariables }] };
}

