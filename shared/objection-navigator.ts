export type NavigatorChannel = 'call' | 'remote' | 'message';

export type NavigatorAnswer = {
  label: string;
  nextStepId?: string;
};

export type NavigatorStep = {
  id: string;
  goal: string;
  text: Partial<Record<NavigatorChannel, string>>;
  requiredVariables: string[];
  answers?: NavigatorAnswer[];
};

export type NavigatorScenarioGroup = 'choice' | 'price' | 'timing' | 'trust' | 'expertise';

export type NavigatorScenario = {
  id: string;
  group: NavigatorScenarioGroup;
  title: string;
  description: string;
  steps: NavigatorStep[];
};

