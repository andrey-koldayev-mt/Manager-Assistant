export function getScenario(scenarioId: string | null | undefined) {
  return OBJECTION_SCENARIOS.find((item) => item.id === scenarioId) ?? null;
}

export function getScenarioStep(scenarioId: string | null | undefined, stepId: string | null | undefined) {
  return getScenario(scenarioId)?.steps.find((step) => step.id === stepId) ?? null;
}

export function getScenarioChannels(scenario: NavigatorScenario | null | undefined): NavigatorChannel[] {
  if (!scenario) return [];
  return [...new Set(scenario.steps.flatMap((step) => Object.keys(step.text) as NavigatorChannel[]))];
}
